/* PS4/PS5 system language ids: 2 fr, 22 fr-CA, 3 es, 20 es-419, 5 it, 8 ru, 7 pt-PT, 17 pt-BR, 10 zh-Hant,
 * 11 zh-Hans, 27 th, 28 vi, everything else English */
int i18n_from_system(int ps) {
  switch (ps) {
    case 2: case 22: return LANG_FR;
    case 3: case 20: return LANG_ES;
    case 5: return LANG_IT;
    case 8: return LANG_RU;
    case 7: case 17: return LANG_PT;
    case 10: case 11: return LANG_ZH;
    case 27: return LANG_TH;
    case 28: return LANG_VI;
    default: return LANG_EN;
  }
}

